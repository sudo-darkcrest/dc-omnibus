#!/usr/bin/env node
/* Datacenter Omnibus build helper (optional; the site already works without it).
   Run `node tools/build.js` after adding or editing a module. It:
   1. writes each module's hidden <script type="application/json" id="module-data"> block
      (glossary, quiz, flashcards) from data/mNN.js, between the module-data markers;
   2. regenerates data/search-index.js (headings + labs of every module) used by index.html and labs.html. */
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = { window: {}, console };
ctx.OMNI = ctx.window.OMNI = { data: {}, register(d) { this.data[d.n] = d; }, registerBank() {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "data/catalog.js"), "utf8"), ctx);
const OMNI = ctx.window.OMNI;
OMNI.register = function (d) { OMNI.data[d.n] = d; };
const strip = s => s.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, " ").trim();
const heads = [], labs = [];
let count = 0;
for (const m of OMNI.catalog) {
  const nn = String(m.n).padStart(2, "0");
  const file = path.join(root, `module-${nn}.html`), dfile = path.join(root, `data/m${nn}.js`);
  if (!fs.existsSync(file)) { console.warn("missing", file); continue; }
  if (fs.existsSync(dfile)) vm.runInContext(fs.readFileSync(dfile, "utf8"), ctx);
  let html = fs.readFileSync(file, "utf8");
  const d = OMNI.data[m.n] || {};
  const payload = { module: m.n, title: m.title, glossary: d.glossary || [], quiz: d.quiz || [], flashcards: d.flashcards || [] };
  const json = JSON.stringify(payload).replace(/</g, "\\u003c");
  const block = `<!-- module-data:start -->\n<script type="application/json" id="module-data">${json}</script>\n<!-- module-data:end -->`;
  html = html.replace(/<!-- module-data:start -->[\s\S]*?<!-- module-data:end -->/, block);
  fs.writeFileSync(file, html);
  // headings: sections with ids
  const secRe = /<section[^>]*\bid="([^"]+)"[^>]*>\s*<h2[^>]*>([\s\S]*?)<\/h2>/g; let r;
  while ((r = secRe.exec(html))) heads.push([m.n, r[1], strip(r[2])]);
  const h3Re = /<h3[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/h3>/g;
  while ((r = h3Re.exec(html))) heads.push([m.n, r[1], strip(r[2])]);
  const labRe = /<div class="lab-card" id="([^"]+)" data-lab="([^"]+)">\s*<h3>([\s\S]*?)<\/h3>/g;
  while ((r = labRe.exec(html))) labs.push([m.n, r[1], strip(r[3]), strip(r[2])]);
  count++;
}
fs.writeFileSync(path.join(root, "data/search-index.js"),
  "/* Generated by tools/build.js. Do not edit by hand. */\nOMNI.headings = " + JSON.stringify(heads) + ";\nOMNI.labs = " + JSON.stringify(labs) + ";\n");
// glossary index for clickable terms (first module that defines a term wins, like OMNI.mergedGlossary)
const slug = t => "g-" + String(t).toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const seen = {}, gidx = [];
for (const m of OMNI.catalog) {
  const d = OMNI.data[m.n]; if (!d || !d.glossary) continue;
  for (const t of d.glossary) { const k = t[0].toLowerCase(); if (seen[k]) continue; seen[k] = 1; gidx.push([t[0], t[3] || "", t[1], slug(t[0]), m.n]); }
}
fs.writeFileSync(path.join(root, "data/glossary-index.js"),
  "/* Generated by tools/build.js. Do not edit by hand. */\nOMNI.glossaryIndex = " + JSON.stringify(gidx) + ";\n");
console.log(`built ${count} modules, ${heads.length} headings, ${labs.length} labs, ${gidx.length} glossary terms`);
